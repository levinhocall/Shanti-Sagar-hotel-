import { test, expect } from '@playwright/test'
const errors = new WeakMap<object, string[]>()
test.beforeEach(async ({ page }) => {
  errors.set(page, [])
  page.on('pageerror', error => errors.get(page)!.push(error.message))
  await page.goto('/')
})
test.afterEach(async ({ page }) => { expect(errors.get(page)).toEqual([]) })

test('hero, navigation, local images and responsive layout', async ({ page }, info) => {
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(/Pure vegetarian\.\s*Pure happiness\./)
  await page.evaluate(() => document.fonts.ready)
  await expect(page.getByRole('img', { name: /Illustrative vegetarian thali/ })).toBeVisible()
  await expect.poll(() => page.getByRole('img', { name: /Illustrative vegetarian thali/ }).evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  expect(await page.evaluate(() => innerWidth)).toBeLessThanOrEqual(info.project.name === 'desktop' ? 1440 : 413)
  if (info.project.name !== 'desktop') {
    await page.getByRole('button', { name: 'Open navigation' }).click()
    await expect(page.getByRole('navigation', { name: 'Mobile navigation' })).toBeVisible()
    await page.getByRole('navigation', { name: 'Mobile navigation' }).getByRole('link', { name: /Menu/ }).click()
    await expect(page.getByRole('navigation', { name: 'Mobile navigation' })).toBeHidden()
    await expect(page).toHaveURL(/#menu/)
    await page.goto('/')
  }
  await page.getByRole('img', { name: /Illustrative vegetarian thali/ }).evaluate((image: HTMLImageElement) => image.decode())
  await expect(page.locator('.hero-copy')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: `test-results/preview-${info.project.name}.png` })
})
test('category filter, immersive details, tabs, browser Back, scroll and focus restoration', async ({ page }) => {
  await page.getByRole('link', { name: 'Explore Menu', exact: true }).click()
  await page.getByRole('button', { name: 'North Indian', exact: true }).click()
  await expect(page.locator('.dish')).toHaveCount(1)
  const card = page.getByRole('button', { name: /Paneer curry/i })
  await card.scrollIntoViewIfNeeded()
  const scroll = await page.evaluate(() => scrollY)
  await card.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(page).toHaveURL(/dish=paneer-curry/)
  await expect(page.getByRole('button', { name: 'Back to the table' })).toBeFocused()
  await page.getByRole('tab', { name: 'Ingredients', exact: true }).click()
  await expect(page.getByRole('tabpanel')).toContainText('No ingredient list')
  await page.getByRole('tab', { name: 'Ingredients', exact: true }).press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Dietary notes' })).toBeFocused()
  await expect(page.getByRole('tabpanel')).toContainText('unverified')
  await page.getByRole('button', { name: 'Next dish image' }).click()
  await expect(dialog.getByRole('img', { name: /visual moodboard, image 2/ })).toBeVisible()
  await page.getByRole('button', { name: 'Back to the table' }).click()
  await expect(dialog).toBeHidden()
  await expect(card).toBeFocused()
  expect(Math.abs(await page.evaluate(() => scrollY) - scroll)).toBeLessThan(10)
  await page.goForward()
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(card).toBeFocused()
})
test('deep-linked dish closes safely and contains keyboard focus', async ({ page }) => {
  await page.goto('/?dish=vegetable-biryani')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  for (let i = 0; i < 14; i++) {
    await page.keyboard.press('Tab')
    expect(await page.evaluate(() => !!document.activeElement?.closest('dialog'))).toBe(true)
  }
  await page.getByRole('button', { name: 'Close dish details' }).click()
  await expect(dialog).toBeHidden()
  await expect(page).not.toHaveURL(/dish=/)
})
test('gallery supports keyboard, swipe, browser history and Escape', async ({ page }) => {
  await page.getByRole('button', { name: 'Open gallery: The art of sharing' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await page.keyboard.press('ArrowRight')
  await expect(page).toHaveURL(/gallery=dosa/)
  await page.locator('.lightbox').dispatchEvent('touchstart', { touches: [{ identifier: 1, clientX: 280, clientY: 200 }] })
  await page.locator('.lightbox').dispatchEvent('touchend', { changedTouches: [{ identifier: 1, clientX: 80, clientY: 200 }] })
  await expect(page).toHaveURL(/gallery=paneer/)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('button', { name: 'Open gallery: The art of sharing' })).toBeFocused()
})
